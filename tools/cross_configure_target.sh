#!/bin/bash
#
# Configure a PixelPilot_rk build against the sbc-groundstations buildroot
# cross toolchain/sysroot (aarch64), for local dev iteration without a board
# or the container_build.sh Debian package flow.
#
# WHY THIS SCRIPT EXISTS (read before deleting it):
#
# This checkout's parent directory has a literal space in its name
# ("openipc@100hz wifilinkvrx"), sitting above both this repo and
# sbc-groundstations. pkg-config emits its -I/-L flags as one plain,
# unquoted, space-joined string, and CMake's FindPkgConfig naively splits
# that string on whitespace -- so any path containing a space gets torn in
# two and silently loses its -I/-L prefix. Symptom: cross-compiling against
# the buildroot sysroot fails with things like
# "fatal error: drm.h: No such file or directory" from xf86drm.h, and gcc
# warnings like "linker input file not found" naming a bare sysroot include
# path with no -I in front of it -- even though the sysroot itself has every
# header/lib pkg-config claims it does.
#
# Fix: route pkg-config through a pkgconf wrapper whose PKG_CONFIG_* env
# vars are unconditionally forced to point at a space-free /tmp mirror of
# the buildroot output tree (a symlink -- pkg-config only ever sees/prints
# the space-free string; the OS resolves the symlink transparently at
# file-open time). The assignments in the wrapper have to be unconditional,
# not `${VAR:-default}`: buildroot's generated toolchainfile.cmake does
# `set(ENV{PKG_CONFIG_SYSROOT_DIR} "<real, space-having path>")` before
# pkg-config ever runs, which silently defeats a fallback-style default.
#
# The wrapper + symlinks live under /tmp, so they don't survive a reboot --
# this script regenerates them and configures a fresh build directory
# against them. Safe to re-run any time.
#
# Usage:
#   tools/cross_configure_target.sh [build_dir] [sbc-groundstations repo dir]
#
# Then: cmake --build <build_dir> --target pixelpilot -j"$(nproc)"

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
BUILD_DIR="${1:-$REPO_DIR/build_target}"
SBC_DIR="${2:-$REPO_DIR/../sbc-groundstations}"
DEFCONFIG="${DEFCONFIG:-runcam_wifilink_defconfig}"

TOOLCHAIN_FILE="$SBC_DIR/output/$DEFCONFIG/host/share/buildroot/toolchainfile.cmake"
if [ ! -f "$TOOLCHAIN_FILE" ]; then
    echo "error: no buildroot toolchain file at: $TOOLCHAIN_FILE" >&2
    echo "       build sbc-groundstations first, or pass its path: $0 <build_dir> <sbc-groundstations dir>" >&2
    exit 1
fi

NOSPACE_ROOT="/tmp/sbc-groundstations-nospace"
PKGCONF_WRAPPER="/tmp/pixelpilot-cross-pkgconf.sh"
HOST_BIN="$NOSPACE_ROOT/output/$DEFCONFIG/host/bin"
SYSROOT="$HOST_BIN/../aarch64-buildroot-linux-gnu/sysroot"

ln -sfn "$SBC_DIR" "$NOSPACE_ROOT"

cat > "$PKGCONF_WRAPPER" <<EOF
#!/bin/sh
# Generated by tools/cross_configure_target.sh -- see that script for why
# this exists. Regenerate with: $SCRIPT_DIR/$(basename "$0")
PKGCONFDIR="$HOST_BIN"
LD_LIBRARY_PATH="\$PKGCONFDIR/../lib:\$LD_LIBRARY_PATH"
PKG_CONFIG_LIBDIR="$SYSROOT/usr/lib/pkgconfig:$SYSROOT/usr/share/pkgconfig"
PKG_CONFIG_SYSROOT_DIR="$SYSROOT"
PKG_CONFIG_SYSTEM_INCLUDE_PATH="$SYSROOT/usr/include"
PKG_CONFIG_SYSTEM_LIBRARY_PATH="$SYSROOT/usr/lib"
export LD_LIBRARY_PATH PKG_CONFIG_LIBDIR PKG_CONFIG_SYSROOT_DIR PKG_CONFIG_SYSTEM_INCLUDE_PATH PKG_CONFIG_SYSTEM_LIBRARY_PATH
exec "\$PKGCONFDIR/pkgconf" --keep-system-libs "\$@"
EOF
chmod +x "$PKGCONF_WRAPPER"

mkdir -p "$BUILD_DIR"
# CMAKE_POLICY_VERSION_MINIMUM=3.5 is unrelated to the space-in-path issue
# above: it's a separate workaround for this project's
# cmake_minimum_required(VERSION 3.1) (CMakeLists.txt:1) being older than
# recent CMake will accept without it. Drop this flag if that line is ever
# bumped.
cmake \
    -DCMAKE_TOOLCHAIN_FILE="$TOOLCHAIN_FILE" \
    -DCMAKE_BUILD_TYPE=Release \
    -DCMAKE_INSTALL_PREFIX=/usr \
    -DPKG_CONFIG_EXECUTABLE="$PKGCONF_WRAPPER" \
    -DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
    -S "$REPO_DIR" -B "$BUILD_DIR"

echo "Configured. Build with: cmake --build \"$BUILD_DIR\" --target pixelpilot -j\$(nproc)"
